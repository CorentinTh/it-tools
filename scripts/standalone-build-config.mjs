import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

import { discoverToolDescriptors, renderToolRegistry } from './generate-tool-registry.mjs';

export const STANDALONE_EXCLUDED_TOOL_DIRECTORIES = [
  'camera-recorder',
  'dns-over-https-query',
  'local-encrypted-otp-vault',
  'mermaid-diagram',
  'offline-geoip-inspector',
  'pdf-signature-checker',
  'text-diff',
];

export async function generateStandaloneToolRegistry({
  outputPath = resolve('src/tools/index.standalone.ts'),
  toolsDirectory = resolve('src/tools'),
} = {}) {
  const excluded = new Set(STANDALONE_EXCLUDED_TOOL_DIRECTORIES);
  const descriptors = (await discoverToolDescriptors(toolsDirectory))
    .filter(descriptor => !excluded.has(descriptor.directoryName));
  const output = renderToolRegistry(descriptors).replace(
    '// This file is generated by scripts/generate-tool-registry.mjs. Do not edit manually.',
    `// Standalone registry excludes: ${STANDALONE_EXCLUDED_TOOL_DIRECTORIES.join(', ')}. Do not edit manually.`,
  );
  await writeFile(outputPath, output);
  return { count: descriptors.length, output };
}
